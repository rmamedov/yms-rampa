<?php

declare(strict_types=1);

namespace App\Domain\Clock;

/**
 * Джерело поточного часу для доменного шару.
 *
 * Домен ніколи не звертається до глобального часу напряму — це робить
 * поведінку ретраїв і планувальника нагадувань детермінованою в тестах.
 * Час ЗАВЖДИ повертається в UTC (конвенція зберігання проєкту).
 */
interface Clock
{
    public function now(): \DateTimeImmutable;
}
