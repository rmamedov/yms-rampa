<?php

declare(strict_types=1);

namespace App\Domain\Store;

/**
 * Перелік магазинів, доступних користувачеві контуру магазину.
 *
 * Окремий порт від StoreConfigProvider навмисно: той відповідає на питання
 * «як влаштована ця філія», а тут — «які філії взагалі існують». Другого
 * питання не можна поставити провайдеру конфігурації, бо для нього треба
 * заздалегідь знати ідентифікатор, а мережеві ролі (super_admin,
 * network_manager) саме його й не мають: їхній скоуп задає РОЛЬ, а не
 * заголовок X-Store-Ids (RBAC-16).
 *
 * @see \App\Infrastructure\Store\FixtureStoreConfigProvider локальна заглушка
 * @see \App\Infrastructure\Store\HttpStoreDirectory         реальний клієнт
 */
interface StoreDirectory
{
    /**
     * Магазини, які беруть участь у роботі (ymsStatus=active із чинною
     * конфігурацією прийому). Магазин на паузі чи без конфігурації у перелік
     * не потрапляє: для нього не існує сітки слотів, тому в перемикачі філії
     * він був би пунктом, що ламає кожен наступний екран.
     *
     * @param list<string>|null $storeIds звуження переліком магазинів зі скоупу;
     *                                    null — без звуження (мережеві ролі).
     *                                    ПОРОЖНІЙ перелік реалізація не отримує:
     *                                    нуль доступу (RBAC-13) вирішується
     *                                    прикладним шаром без звернення до сусіда
     *
     * @return list<StoreBrief>
     */
    public function listStores(?array $storeIds = null): array;
}
